export type TemplateValue = string | number

export type TemplateValues = Readonly<Record<string, TemplateValue>>

/**
 * Zero-dependency ICU-subset message template formatter supporting `{param}`
 * interpolation and `{count, plural, one {...} other {...}}` blocks.
 */
export const formatTemplate = (template: string, values?: TemplateValues): string => {
  if (values === undefined) return template
  const withPlurals = template.replace(
    /\{(\w+),\s*plural,\s*one\s*\{([^}]*)\}\s*other\s*\{([^}]*)\}\s*\}/g,
    (_full, key: string, one: string, other: string) => {
      const raw = values[key]
      const count = typeof raw === "number" ? raw : Number(raw ?? 0)
      return (count === 1 ? one : other).replaceAll("#", String(raw ?? ""))
    }
  )
  return withPlurals.replace(/\{(\w+)\}/g, (_full, key: string) => {
    const val = values[key]
    return val === undefined ? `{${key}}` : String(val)
  })
}

